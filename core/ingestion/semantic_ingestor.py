import os
import glob
import pandas as pd
import duckdb
from datetime import datetime, timezone

class SemanticIngestor:
    def __init__(self, db_path: str = "data/duckdb/intelligence.duckdb"):
        self.db_path = db_path
        
    def ingest_corporate_actions(self, ca_dir: str = "data/parquet/corporate_actions"):
        """
        Reads Corporate Action Parquet files generated by MarketDataIngestor
        and translates them into Information Events in the DuckDB Ledger.
        """
        if not os.path.exists(ca_dir):
            print(f"Corporate Actions directory {ca_dir} does not exist.")
            return
            
        con = duckdb.connect(self.db_path)
        
        ca_files = glob.glob(os.path.join(ca_dir, "*.parquet"))
        total_ingested = 0
        
        for file in ca_files:
            try:
                df = pd.read_parquet(file)
                if df.empty:
                    continue
                    
                for _, row in df.iterrows():
                    event_id = row['corporate_action_id']
                    ticker = row['entity_id']
                    entity_id = f"ENT_{ticker}"
                    action_type = row['action_type']
                    effective_date = row['effective_date']
                    value = row['value']
                    retrieved_at = row['retrieved_at']
                    
                    # For dividends/splits historically sourced, we assume published_at = effective_date
                    # In a real environment, publication_time (ex-date / announcement date) would be much earlier
                    published_at = effective_date
                    information_available_at = published_at
                    observed_at = retrieved_at
                    
                    # Prepare description for raw_reference
                    description = f"Corporate Action: {action_type} of {value} for {ticker}"
                    
                    # Upsert (using INSERT OR IGNORE / ON CONFLICT logic)
                    con.execute("""
                        INSERT INTO fact_event (
                            event_id, event_type, event_subtype, 
                            entity_id, entity_type, 
                            event_timestamp, published_at, information_available_at, observed_at, retrieved_at,
                            valid_from, valid_to,
                            source_id, source_name, source_quality, source_type,
                            raw_reference, provenance,
                            information_state, information_delta,
                            materiality, relevance, confidence,
                            is_pit_valid, status
                        ) VALUES (
                            ?, ?, ?,
                            ?, ?,
                            ?, ?, ?, ?, ?,
                            ?, NULL,
                            ?, ?, ?, ?,
                            ?, ?,
                            ?, ?,
                            ?, ?, ?,
                            ?, ?
                        ) ON CONFLICT (event_id) DO NOTHING;
                    """, (
                        event_id, 'CORPORATE_ACTION', action_type,
                        entity_id, 'COMPANY',
                        effective_date, published_at, information_available_at, observed_at, retrieved_at,
                        published_at, # valid_from
                        'SRC_YFINANCE_MARKET', 'Yahoo Finance', 'HIGH', 'official exchange/regulator',
                        description, 'REAL',
                        'CONFIRMED', 'NEW',
                        'HIGH', 'HIGH', 0.95,
                        True, 'ACTIVE'
                    ))
                    total_ingested += 1
            except Exception as e:
                print(f"Error ingesting {file}: {e}")
                
        con.close()
        print(f"Ingested {total_ingested} corporate action events into fact_event.")
        return total_ingested

if __name__ == "__main__":
    ingestor = SemanticIngestor()
    ingestor.ingest_corporate_actions()
